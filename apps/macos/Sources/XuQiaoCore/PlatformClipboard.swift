/// 每次会话/策略变化立即失效。锁覆盖系统调用入口，关闭后旧的主线程回调不能再写入。
final class ClipboardPermit {
    private let lock = NSLock()
    private var valid = true
    func cancel() { lock.lock(); valid = false; lock.unlock() }
    func perform<T>(_ body: () -> T) -> T? {
        lock.lock(); defer { lock.unlock() }; guard valid else { return nil }; return body()
    }
}

/// 所有 NSPasteboard 接触都在主线程；后台仅指应用后台，锁屏/用户切换会停用。
final class PlatformClipboard {
    private let boardName: String?
    private var board: NSPasteboard { boardName.map { NSPasteboard(name: .init($0)) } ?? .general }
    private var active = false
    private var observing = false
    private var timer: Timer?
    private var baseline = 0
    private var ownCounts = Set<Int>()
    private var observers: [NSObjectProtocol] = []
    private var observerEpoch = UUID()
    var onRuntime: ((Bool) -> Void)?
    var onCapture: ((UUID, Int, ClipboardCapture) -> Void)?
    init(name: String?) { boardName = name }
    static func validTestName(_ name: String) -> Bool {
        // 只接收命名板标识，不允许系统板别名或不可见字符。
        let system = ["general", "find", "drag", "font", "ruler", "nsgeneralpboard", "nsfindpboard", "nsdragpboard", "nsfontpboard", "nsrulerpboard", "com.apple.pasteboard.general", "com.apple.pasteboard.find", "com.apple.pasteboard.drag"]
        return (1...128).contains(name.utf8.count) && !system.contains(name.lowercased()) && !name.lowercased().hasPrefix("com.apple.") && name.utf8.allSatisfy { (48...57).contains($0) || (65...90).contains($0) || (97...122).contains($0) || [45, 46, 95].contains($0) }
    }
    deinit {
        let tokens = observers, sourceTimer = timer
        DispatchQueue.main.async {
            sourceTimer?.invalidate()
            for token in tokens {
                NSWorkspace.shared.notificationCenter.removeObserver(token)
                DistributedNotificationCenter.default().removeObserver(token)
            }
        }
    }
    func start() {
        DispatchQueue.main.async { [weak self] in
            guard let self else { return }
            let workspace = NSWorkspace.shared.notificationCenter
            self.observers.append(workspace.addObserver(forName: NSWorkspace.sessionDidResignActiveNotification, object: nil, queue: .main) { [weak self] _ in self?.setActive(false) })
            self.observers.append(workspace.addObserver(forName: NSWorkspace.sessionDidBecomeActiveNotification, object: nil, queue: .main) { [weak self] _ in self?.refreshRuntime() })
            let distributed = DistributedNotificationCenter.default()
            self.observers.append(distributed.addObserver(forName: .init("com.apple.screenIsLocked"), object: nil, queue: .main) { [weak self] _ in self?.setActive(false) })
            self.observers.append(distributed.addObserver(forName: .init("com.apple.screenIsUnlocked"), object: nil, queue: .main) { [weak self] _ in self?.refreshRuntime() })
            self.refreshRuntime()
        }
    }
    private func refreshRuntime() {
        let info = CGSessionCopyCurrentDictionary() as? [String: Any]
        setActive(info?["CGSSessionScreenIsLocked"] as? Bool != true && info?[kCGSessionOnConsoleKey as String] as? Bool == true)
    }
    private func setActive(_ value: Bool) {
        if active == value { onRuntime?(value); return }
        active = value; ownCounts.removeAll(); timer?.invalidate(); timer = nil
        if active && observing { installTimer() }
        onRuntime?(value)
    }
    func observe(_ enabled: Bool, epoch: UUID) {
        DispatchQueue.main.async { [weak self] in
            guard let self else { return }
            guard self.observing != enabled || self.observerEpoch != epoch else { return }
            self.observing = enabled; self.observerEpoch = epoch
            self.timer?.invalidate(); self.timer = nil; self.ownCounts.removeAll()
            if enabled && self.active { self.installTimer() }
        }
    }
    private func installTimer() {
        baseline = board.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.3, repeats: true) { [weak self] _ in self?.poll() }
    }
    private func poll() {
        guard active, observing else { return }
        let count = board.changeCount; guard count != baseline else { return }; baseline = count
        if ownCounts.remove(count) != nil { return }
        if let capture = capture(automatic: true) { onCapture?(observerEpoch, count, capture) }
    }
    private func capture(automatic: Bool) -> ClipboardCapture? {
        let types = board.types ?? []
        if automatic && types.contains(where: { ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"].contains($0.rawValue) }) { return nil }
        if let urls = board.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            guard urls.count <= GROUP_MAX_ROOTS, urls.allSatisfy(\.isFileURL) else { return nil }; return .paths(urls)
        }
        if types.contains(where: { ["NSFilesPromisePboardType", "com.apple.pasteboard.promised-file-url", "com.apple.pasteboard.promised-file-content-type", "NSFilenamesPboardType"].contains($0.rawValue) }) { return nil }
        let imageTypes = types.filter { UTType($0.rawValue)?.conforms(to: .image) == true }
        if !imageTypes.isEmpty {
            let preferred = imageTypes.sorted { ($0 == .png ? 0 : $0 == .tiff ? 1 : 2) < ($1 == .png ? 0 : $1 == .tiff ? 1 : 2) }
            for type in preferred {
                if let bytes = board.data(forType: type), !bytes.isEmpty, bytes.count <= FILE_MAX_SIZE { return .image(bytes) }
            }
            return nil
        }
        guard types.contains(.string), let bytes = board.data(forType: .string),
              (1...clipboardLimit).contains(bytes.count), !bytes.contains(0) else { return nil }
        let text = String(decoding: bytes, as: UTF8.self)
        return Data(text.utf8) == bytes ? .text(text) : nil
    }
    func readCapture(permit: ClipboardPermit, completion: @escaping (ClipboardCapture?) -> Void) {
        DispatchQueue.main.async { [weak self] in
            guard let self, self.active else { completion(nil); return }
            completion(permit.perform { self.capture(automatic: false) } ?? nil)
        }
    }
    func changeCount(permit: ClipboardPermit, completion: @escaping (Int?) -> Void) {
        DispatchQueue.main.async { [weak self] in
            guard let self, self.active else { completion(nil); return }
            completion(permit.perform { self.board.changeCount })
        }
    }
    func write(_ text: String, permit: ClipboardPermit, markOwn: Bool = true, completion: @escaping (Bool?) -> Void) {
        DispatchQueue.main.async { [weak self] in
            guard let self, self.active else { completion(false); return }
            let result = permit.perform {
                self.board.clearContents()
                let ok = self.board.setString(text, forType: .string)
                if ok && markOwn {
                    self.ownCounts.insert(self.board.changeCount)
                    if self.ownCounts.count > 128 { self.ownCounts = [self.board.changeCount] }
                }
                return ok
            }
            completion(result)
        }
    }
}

extension PlatformClipboard {
    func writeContent(_ capture: ClipboardCapture, permit: ClipboardPermit, completion: @escaping (Bool?) -> Void) {
        if case .text(let text) = capture { write(text, permit: permit, completion: completion); return }
        DispatchQueue.main.async { [weak self] in
            guard let self, self.active else { completion(false); return }
            completion(permit.perform {
                self.board.clearContents()
                let success: Bool
                switch capture {
                case .paths(let urls): success = self.board.writeObjects(urls as [NSURL])
                case .image(let bytes): success = self.board.setData(bytes, forType: .png)
                case .text: success = false
                }
                if success { self.ownCounts.insert(self.board.changeCount); if self.ownCounts.count > 128 { self.ownCounts = [self.board.changeCount] } }
                return success
            })
        }
    }
}
